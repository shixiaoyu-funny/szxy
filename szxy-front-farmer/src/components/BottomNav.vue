<script setup lang="ts">
import { ref, onMounted, watch } from 'vue'
import { useRoute, useRouter } from 'vue-router'
import { useUserStore } from '../stores/user'
import { getVillageInfo } from '../api/user'

const route = useRoute()
const router = useRouter()
const userStore = useUserStore()

const isVillageAssigned = ref(true)
const currentRoute = ref(route.path)

// 检查用户是否有归属农村
const checkVillageAssignment = async () => {
  if (userStore.isLoggedIn && userStore.userInfo && userStore.userInfo.type === 2) {
    try {
      const res = await getVillageInfo()
      isVillageAssigned.value = !!res.data
    } catch (error) {
      console.error('检查农村归属信息失败:', error)
      // 如果检查失败，默认认为有归属，避免阻塞用户
      isVillageAssigned.value = true
    }
  } else {
    // 非农户用户默认不受此限制
    isVillageAssigned.value = true
  }
}

// 处理导航点击
const handleNavigation = (isDisabled: boolean, targetPath: string) => {
  if (isDisabled) {
    // 如果被禁用，提示用户需要先申请农村归属
    alert('请先完成农户资质申请，获得农村归属后才能访问该功能')
    router.push('/village-manage')
  } else {
    router.push(targetPath)
  }
}

onMounted(async () => {
  await checkVillageAssignment()
})

// 监听路由变化
watch(
  () => route.path,
  (newPath) => {
    currentRoute.value = newPath
    
    // 当进入农村管理页面时，重新检查归属状态
    if (newPath === '/village-manage') {
      setTimeout(async () => {
        await checkVillageAssignment()
      }, 1000) // 延迟执行，确保页面数据已更新
    }
  }
)
</script>

